"""Original music beds, ducked under the voice.

The three beds are generated by `tools/make_music.py` from sine/saw voices and
synthetic drums: no samples, no attribution, no network. They are deliberately
simple -- a bed at -34 dB under speech only has to establish a mood and give the
ear a floor, not compete with the dialogue.
"""

from __future__ import annotations

import os

MUSIC_DIR = os.path.abspath(os.path.join(
    os.path.dirname(__file__), "..", "..", "assets", "music"))

# Genre -> bed. Gameplay gets the pulse because game audio is already busy;
# a lofi loop under a podcast leaves the voice clearly on top.
_BY_GENRE = {
    "gaming": "pulse.wav",
    "podcast": "lofi.wav",
    "talking_head": "lofi.wav",
    "general": "cinematic.wav",
}


# Real tracks beat generated beds. Drop royalty-free files you have the rights
# to into assets/music/<genre>/ (gaming, podcast, general) and they are used in
# preference to the built-in loops, rotated across a job's clips so a batch of
# five does not share one song. Nothing else needs configuring.
TRACK_EXTENSIONS = (".mp3", ".wav", ".m4a", ".aac", ".ogg", ".flac")


def _library(genre: str) -> list:
    folder = os.path.join(MUSIC_DIR, genre)
    if not os.path.isdir(folder):
        return []
    return sorted(os.path.join(folder, f) for f in os.listdir(folder)
                  if f.lower().endswith(TRACK_EXTENSIONS))


def path_for(genre: str = "", title: str = "", variant: int = 0) -> str | None:
    key = (genre or "").strip().lower()
    text = f" {title or ''} ".lower()
    if "gta" in text or "grand theft auto" in text:
        key = "gaming"
    folder = {"talking_head": "podcast"}.get(key, key) or "general"
    tracks = _library(folder) or _library("general")
    if tracks:
        return tracks[variant % len(tracks)]
    name = _BY_GENRE.get(key, "cinematic.wav")
    path = os.path.join(MUSIC_DIR, name)
    return path if os.path.exists(path) else None


def gain_for(genre: str = "") -> float:
    """Bed level before ducking. Gameplay needs less; it has its own audio."""
    return 0.12 if (genre or "").lower() == "gaming" else 0.17
